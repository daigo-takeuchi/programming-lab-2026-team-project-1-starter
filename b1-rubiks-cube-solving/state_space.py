# B1：ルービックキューブの状態数（状態空間の大きさ）
#
# 「状態数」は数え方の定義によって変わる。ここでは次の定義を使う。
#   - キューブの面を回す操作だけで到達できる状態を数える（分解して組み直した状態は含めない）
#   - キューブ全体の持ち替え（空間内での向きの違い）は同じ状態とみなす
#   - 同じ色のセンターパーツは区別しない（4×4×4）
#   - センターパーツの向き（模様がある場合など）は区別しない
#
# 出典：Wikipedia（英語版）"Pocket Cube"、"Rubik's Cube"、"Rubik's Revenge"（2026年11月参照）

from math import factorial


def states_2x2x2():
    """2×2×2 の合法状態数：8! × 3^7 / 24 = 7! × 3^6 = 3,674,160

    - コーナー8個の並べ方：8!（奇置換も可能）
    - コーナーの向き：7個は自由に決められ、最後の1個は他の7個で決まる → 3^7
    - 固定されたセンターがないため、キューブ全体の向き24通りを同一視して 24 で割る
    """
    return factorial(8) * 3**7 // 24


def states_3x3x3():
    """3×3×3 の合法状態数：8! × 3^7 × 12! × 2^11 / 2 = 43,252,003,274,489,856,000

    - コーナーの並べ方 8!、向き 3^7
    - エッジの並べ方 12!、向き 2^11
    - コーナーとエッジの置換の偶奇は一致しなければならない → 2 で割る
    - センターは固定されている（キューブの向きはセンターで決まる）
    """
    return (
        factorial(8) * 3**7
        * factorial(12) * 2**11
        // 2
    )


def states_4x4x4():
    """4×4×4 の合法状態数：8! × 3^7 × 24!^2 / ((4!)^6 × 24)
                         = 7,401,196,841,564,901,869,874,093,974,498,574,336,000,000,000（約 7.40 × 10^45）

    - コーナーの並べ方 8!、向き 3^7
    - エッジ24個の並べ方 24!（エッジは内部の形のため反転できない）
    - センター24個の並べ方 24!。ただし同じ色の4個は区別しないので (4!)^6 で割る
    - 固定されたセンターがないため、キューブ全体の向き24通りを同一視して 24 で割る
    """
    return (
        factorial(8) * 3**7
        * factorial(24) ** 2
        // (factorial(4) ** 6 * 24)
    )


