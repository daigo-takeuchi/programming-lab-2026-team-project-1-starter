# B2：探索空間の大きさ（候補配置数）
#
# 注意：ここで計算するのは、制約（辺の整合性・外周条件）を無視した「候補配置数」であり、
#       合法な完成状態の数ではない。

from math import factorial


def count_arrangements(n):
    """回転なし：N 個の異なるピースを N 個の位置に並べる方法の数 N!"""
    return factorial(n)


def count_arrangements_with_rotation(n):
    """回転あり：各ピースの4方向の回転を区別した場合の候補数の上限 N! × 4^N

    対称なピースや、同一視できる配置がある場合、異なる実状態の数はこれより少なくなる。
    """
    return factorial(n) * (4 ** n)


