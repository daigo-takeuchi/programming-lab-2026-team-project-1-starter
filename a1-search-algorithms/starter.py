# A1：線形探索と二分探索の性能比較 — starter code
#
# 教科書の2つの探索関数を、同じデータ・同じ探索対象で動かして比較する。
#   seq_search : 線形探索（先頭から1つずつ調べる）
#   bin_search : 二分探索（探索範囲を半分ずつ絞り込む）
# どちらも、見つかればその要素のインデックスを、見つからなければ -1 を返す。
#
# 二分探索の前提条件：
#   - 線形探索は、未整列のデータにも適用できる。
#   - 二分探索は、昇順に整列済みのデータを前提とする。
#   - 今回は両アルゴリズムの比較条件を揃えるため、同じ整列済みデータを使用する。
#   - 二分探索のためのソート処理は、この基本動作の比較には含めない。

from textbook.ssearch_while import seq_search
from textbook.bsearch import bin_search

data = [2, 5, 8, 12, 17, 21, 30]   # 昇順に整列済みのデータ

print("Data:", data)
print()

# 2：先頭の要素、17：中央付近の要素、30：末尾の要素、99：存在しない要素
for key in [2, 17, 30, 99]:
    linear_result = seq_search(data, key)
    binary_result = bin_search(data, key)

    print(f"Target: {key}")
    print(f"  Linear Search: {linear_result}")
    print(f"  Binary Search: {binary_result}")


